"""Refresh the home page's LinkedIn news from the company's public LinkedIn page.

    python tools/linkedin_sync.py          (needs Python 3.11+ and Pillow: pip install pillow)
    node build.mjs

Reads the recent posts that https://www.linkedin.com/company/hamdaz-technologies/ shows to visitors who are not
signed in (about the last ten), saves each post's text, date, link and reactions to src/content/linkedin.mjs, and
its photos (up to four, as WebP no wider than 900px) to assets/img/linkedin/. Photos of posts that dropped off the
list are deleted. Nothing is written if the page could not be read, so a failed run leaves the site as it was.

This is a stop-gap: once LinkedIn approves the Community Management API for the company page, the ERP can fetch
the same posts with the API and this script can go.
"""
import datetime, html, io, json, os, re, sys, urllib.request

from PIL import Image

PAGE = 'https://www.linkedin.com/company/hamdaz-technologies/'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG_DIR = os.path.join(ROOT, 'assets', 'img', 'linkedin')
OUT = os.path.join(ROOT, 'src', 'content', 'linkedin.mjs')
UA = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36',
      'Accept-Language': 'en-US,en;q=0.9'}


def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=40).read()


def posts_from(page):
    posts = []
    for m in re.finditer(r'<article[^>]*data-activity-urn="urn:li:activity:(\d+)"[^>]*data-attributed-urn="urn:li:(?:share|ugcPost):\d+"[^>]*>(.*?)</article>', page, re.S):
        aid, art = m.group(1), m.group(2)
        # the card's link to the post sits just before the article
        link = re.findall(r'href="(https://www\.linkedin\.com/posts/[^"?]+)', page[max(0, m.start() - 1500):m.start()])
        t = re.search(r'attributed-text-segment-list__content[^>]*>(.*?)</p>', art, re.S)
        text = ''
        if t:
            text = html.unescape(re.sub(r'<[^>]+>', '', re.sub(r'<br\s*/?>', '\n', t.group(1))))
            text = '\n'.join(' '.join(line.split()) for line in text.split('\n')).strip()
        images = list(dict.fromkeys(html.unescape(u) for u in re.findall(
            r'data-delayed-url="(https://media\.licdn\.com/dms/image/[^"]+(?:feedshare|image-shrink)[^"]*)"', art)))
        react = re.search(r'data-num-reactions="(\d+)"', art)
        posts.append({
            'id': aid,
            # a LinkedIn id carries its time: the top bits are milliseconds since 1970
            'date': datetime.datetime.fromtimestamp((int(aid) >> 22) / 1000, datetime.UTC).strftime('%Y-%m-%d'),
            'url': link[-1] if link else f'https://www.linkedin.com/feed/update/urn:li:activity:{aid}/',
            'text': text,
            'reactions': int(react.group(1)) if react else 0,
            'imageCount': len(images),
            'sources': images[:4],
        })
    return posts


def main():
    page = get(PAGE).decode('utf-8', 'ignore')
    posts = [p for p in posts_from(page) if p['text']]
    if not posts:
        sys.exit('No posts found on the LinkedIn page (it may have changed, or asked to sign in). Nothing was changed.')

    os.makedirs(IMG_DIR, exist_ok=True)
    keep = set()
    for p in posts:
        files = []
        for n, src in enumerate(p.pop('sources')):
            name = f"{p['id']}-{n + 1}.webp"
            path = os.path.join(IMG_DIR, name)
            if not os.path.exists(path):
                im = Image.open(io.BytesIO(get(src))).convert('RGB')
                im.thumbnail((900, 900))
                im.save(path, 'WEBP', quality=78, method=6)
            with Image.open(path) as im:
                files.append({'src': f'assets/img/linkedin/{name}', 'w': im.width, 'h': im.height})
            keep.add(name)
        p['images'] = files
    for name in os.listdir(IMG_DIR):
        if name.endswith('.webp') and name not in keep:
            os.remove(os.path.join(IMG_DIR, name))

    stamp = datetime.datetime.now(datetime.UTC).strftime('%Y-%m-%d')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(f'// Generated by tools/linkedin_sync.py on {stamp} from the public LinkedIn company page. Do not edit by hand:\n')
        f.write('// run the script again to refresh. Newest first.\n')
        f.write(f'export const linkedinNews = {json.dumps(posts, ensure_ascii=False, indent=2)};\n')
    print(f'{len(posts)} posts, {len(keep)} photos -> {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
